/* Final checks that span modules, the validation report and the README. */
COMPANY.finish = ctx => {
  const { CO, byId } = ctx;
  ctx.step = "org";
  let bad = ctx.owners.filter(o => !byId[o.id] || byId[o.id].status !== "active");
  COMPANY.check(ctx, "Every owner is an active person", !bad.length, bad.slice(0, 5).map(o => `${o.id} (${o.what})`).join(", "));
  bad = ctx.owners.filter(o => byId[o.id] && byId[o.id].status === "terminated");
  COMPANY.check(ctx, "Terminated people own nothing", !bad.length, bad.slice(0, 5).map(o => `${o.id} (${o.what})`).join(", "));

  const ok = COMPANY.ok(ctx);
  const esc = s => String(s).replace(/\|/g, "\\|");
  const L = [];
  L.push(`# Validation report: ${CO.name}`, "", `Profile \`${ctx.profileName}\`, seed ${ctx.SEED}, as of ${ctx.AS_OF}. Result: **${ok ? "PASS" : "FAIL"}**`, "");
  L.push(`Modules: ${ctx.modules.map(m => m.title).join(", ")}`, "");
  L.push("## Checks", "| Check | Result | Detail |", "|---|---|---|");
  for (const c of ctx.checks) L.push(`| ${c.name} | ${c.ok ? "Pass" : "**Fail**"} | ${esc(c.detail)} |`);
  L.push("", "## Counts", "| File | Rows |", "|---|---|");
  for (const k of COMPANY.sortStr(Object.keys(ctx.tables))) L.push(`| \`${k}\` | ${ctx.tables[k].rows.length} |`);
  const people = ctx.people, active = people.filter(p => p.status !== "terminated"), term = people.filter(p => p.status === "terminated");
  const byYear = {};
  for (const p of term) { const y = (p.term || "unknown").slice(0, 4); byYear[y] = (byYear[y] || 0) + 1; }
  L.push("", "## People",
    `- Active (incl. on leave): ${active.length}; on leave: ${people.filter(p => p.status === "on_leave").length}; contractors: ${active.filter(p => p.kind === "contractor").length}`,
    `- Terminated (kept): ${term.length} — ${Object.keys(byYear).sort().map(y => `${y}: ${byYear[y]}`).join(", ")}`,
    `- Vendor contacts: ${ctx.vendorContacts.length}`,
    `- Named positions: ${Object.values(ctx.byPos).reduce((s, v) => s + v.length, 0)}`, "",
    "| Site | Active |", "|---|---|");
  for (const s of COMPANY.sortStr(Object.keys(ctx.siteCounts))) L.push(`| ${s} | ${ctx.siteCounts[s]} |`);
  const div = {};
  for (const p of active) { const n = (ctx.UNITS[ctx.divisionOf(p.unit)] || { name: "(unknown unit)" }).name; div[n] = (div[n] || 0) + 1; }
  L.push("", "| Division | Active |", "|---|---|");
  for (const [k, v] of Object.entries(div).sort((a, b) => b[1] - a[1])) L.push(`| ${k} | ${v} |`);
  ctx.report = L.join("\n") + "\n";

  const order = ["business_units", "facilities_sites", "facilities_buildings", "facilities_secure_areas", "people", "people_hr", "groups", "group_members",
    "data_types", "vendors", "products", "services", "business_functions", "applications", "application_roles", "assets"]
    .filter(f => ctx.tables[`${f}.csv`]);
  const links = Object.keys(ctx.tables).some(f => f.startsWith("links_"));
  ctx.readme = `# ${CO.name}: synthetic data

**Everything in these files is fictional.** ${CO.name} does not exist. People, emails (\`.example\` domains), phone numbers,
addresses, IDs and history are invented. Real product and vendor names (e.g. AWS, Okta, Workday) are used for realism only:
tiers, contracts, scores and any findings about them are invented. Vendors marked \`name_is_real_company = No\` are fictional.

Generated by the Synthetic Data Generator from \`${ctx.profileName}\` with seed ${ctx.SEED}, as of ${ctx.AS_OF}. Same profile and seed give the same files.
Modules: ${ctx.modules.map(m => m.title).join(", ")}.

Load order for the GRC platform's Foundation import: ${order.join(", ")}${links ? ", then the links_* files" : ""}.
\`business_units.head_employee_id\`${ctx.tables["facilities_sites.csv"] ? " and `facilities_sites.facility_manager_employee_id`" : ""} refer to people: load them after people
or as a second pass.

See validation-report.md for the checks.
`;
};
