// Bundles example profiles as .js so the page can load them offline and from file://.
// Run after editing a profile:  node tools/bundle-profiles.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const PROFILES = [
  { name: "larkspur-pay.profile.yaml", title: "Larkspur Pay", src: "docs/requirements/larkspur-pay.profile.yaml", out: "profiles/larkspur-pay.js" },
];
export const bundle = p => {
  const text = readFileSync(path.join(root, p.src), "utf8").replace(/\r\n/g, "\n");
  return `/* Generated by tools/bundle-profiles.mjs from ${p.src}. Do not edit; edit the YAML and re-run. */\n` +
    `(window.COMPANY_PROFILES = window.COMPANY_PROFILES || {})[${JSON.stringify(p.name)}] = { title: ${JSON.stringify(p.title)}, text: ${JSON.stringify(text)} };\n`;
};
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  mkdirSync(path.join(root, "profiles"), { recursive: true });
  for (const p of PROFILES) { writeFileSync(path.join(root, p.out), bundle(p)); console.log("wrote", p.out); }
}
